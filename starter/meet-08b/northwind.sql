BEGIN;

CREATE TABLE IF NOT EXISTS categories (
    category_id INTEGER PRIMARY KEY,
    category_name TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS suppliers (
    supplier_id INTEGER PRIMARY KEY,
    company_name TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS products (
    product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name TEXT NOT NULL CHECK (length(trim(product_name)) BETWEEN 1 AND 40),
    supplier_id INTEGER NOT NULL REFERENCES suppliers(supplier_id),
    category_id INTEGER NOT NULL REFERENCES categories(category_id),
    quantity_per_unit TEXT NOT NULL DEFAULT '' CHECK (length(quantity_per_unit) <= 20),
    unit_price NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (unit_price >= 0),
    units_in_stock INTEGER NOT NULL DEFAULT 0 CHECK (units_in_stock BETWEEN 0 AND 32767),
    units_on_order INTEGER NOT NULL DEFAULT 0 CHECK (units_on_order BETWEEN 0 AND 32767),
    reorder_level INTEGER NOT NULL DEFAULT 0 CHECK (reorder_level BETWEEN 0 AND 32767),
    discontinued INTEGER NOT NULL DEFAULT 0 CHECK (discontinued IN (0, 1))
);

